// Writes the package.json version to src/version.ts and server.json. Runs
// automatically on `npm version`.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
writeFileSync(
  new URL('../src/version.ts', import.meta.url),
  `// Generated by scripts/sync-version.mjs from package.json. Do not edit.\nexport const VERSION = '${version}';\n`,
);

const serverJsonUrl = new URL('../server.json', import.meta.url);
const serverJson = readFileSync(serverJsonUrl, 'utf8');
writeFileSync(serverJsonUrl, serverJson.replace(/("version":\s*")[^"]*(")/, `$1${version}$2`));
